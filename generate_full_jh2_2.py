def add_q(page, kind, label, top, bottom, left, right, body, answer,
          steps=None, advanced_steps=None, sol_custom=False):
    slug = label.replace(" ", "_").replace("（", "_").replace("）", "_").replace("、", "_").replace("／", "_")
    qid = f"jh2_2-p{page}-{label}"
    q_img_rel = f"crops/jh2_2-p{page}-{slug}.jpg"
    a_img_rel = f"crops/jh2_2-p{page}-{slug}_sol.jpg"
    
    q_dest = os.path.join(WEB, q_img_rel.replace('/', os.sep))
    a_dest = os.path.join(WEB, a_img_rel.replace('/', os.sep))
    
    q_full = get_q_img(page)
    a_full = get_a_img(page)
    w, h = q_full.size
    
    box_q = (int(left * w), int(top * h), int(right * w), int(bottom * h))
    q_full.crop(box_q).save(q_dest, quality=88)
    
    if sol_custom and steps:
        make_full_solution_card(label, answer, steps, advanced_steps, a_dest)
    else:
        crop_a = a_full.crop(box_q)
        append_advanced_card(crop_a, advanced_steps, a_dest)
        
    questions_2_2.append({
        "id": qid,
        "zone": "jh2_2",
        "asset": "1上國中講義數學測驗卷.pdf",
        "page": page,
        "kind": kind,
        "label": label,
        "top": round(top, 4),
        "bottom": round(bottom, 4),
        "left": round(left, 4),
        "right": round(right, 4),
        "body": body,
        "answer": answer,
        "image": q_img_rel,
        "solutionImage": a_img_rel,
    })
    
    crops_entries.append({
        "pdf": "1上國中講義數學測驗卷.pdf",
        "page": page,
        "top": round(top, 4),
        "bottom": round(bottom, 4),
        "left": round(left, 4),
        "right": round(right, 4),
        "out": q_img_rel
    })
    crops_entries.append({
        "pdf": "1上國中講義數學測驗卷解答.pdf",
        "page": page,
        "top": round(top, 4),
        "bottom": round(bottom, 4),
        "left": round(left, 4),
        "right": round(right, 4),
        "out": a_img_rel
    })

